-- Второй фактор отмечается на самой сессии (итоговая проверка вехи M1, решение 0014).
-- До этого рабочее место проверяло только признак учётной записи twoFactorEnabled: сессия, открытая
-- одним паролем до подключения второго фактора, становилась полной сессией сотрудника, как только
-- второй фактор подключали в другом браузере.
ALTER TABLE auth."session" ADD COLUMN "secondFactorAt" timestamptz;

COMMENT ON COLUMN auth."session"."secondFactorAt" IS 'Колонка портала. Когда в этой сессии предъявлен код второго фактора. Пусто у сессии, открытой одним паролем: рабочее место она не открывает';
