-- Чтение обращений сотрудниками в журнале аудита (аудит 23.11.2026, находка S8; план W1, задача 8).
-- Запись ticket.viewed_by_staff пишется не чаще раза в час на пару сотрудник и обращение: время последней записи
-- хранится рядом с отметкой "просмотрено". Строка может появиться раньше отметки (сотрудник открыл обращение, запись
-- в журнал сделана, а отметку "просмотрено" страница ещё не поставила), поэтому seen_on больше не обязателен.

ALTER TABLE hdt_ticket_reads ADD COLUMN view_logged_on timestamptz;
ALTER TABLE hdt_ticket_reads ALTER COLUMN seen_on DROP NOT NULL;

COMMENT ON COLUMN hdt_ticket_reads.view_logged_on IS 'Когда открытие обращения этим сотрудником последний раз записано в журнал аудита';
COMMENT ON COLUMN hdt_ticket_reads.seen_on IS 'Когда сотрудник последний раз открывал обращение. Пусто: отметка ещё не поставлена';
