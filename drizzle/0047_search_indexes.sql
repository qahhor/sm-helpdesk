-- Индексы поиска людей (аудит 23.11.2026, находка P9; план W2, задача 4). Файл выполняется вне транзакции
-- (решение 0039, пункт 1). Сотрудник ищет автора обращения по части имени или подтверждённого адреса: таблица
-- пользователей просматривалась целиком. Запрос короче трёх знаков портал не ищет: триграммный индекс ему не помогает.
--
-- Для таблиц с политиками RLS (организации, обращения) такой индекс сейчас не работает: PostgreSQL не выполняет
-- оператор ILIKE раньше условий политики и поэтому не берёт его в условие индекса (решение 0039, пункт 6).
-- У таблицы пользователей политик RLS нет: её читает только роль входа.
CREATE INDEX CONCURRENTLY IF NOT EXISTS user_name_trgm_idx ON auth."user" USING gin (name gin_trgm_ops);
CREATE INDEX CONCURRENTLY IF NOT EXISTS user_email_trgm_idx ON auth."user" USING gin (email gin_trgm_ops);
