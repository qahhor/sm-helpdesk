-- Второй замок на удаление журнала аудита (итоговая проверка волны 4; решение 0041, пункт 4).
-- Разрешающие политики складываются по "или": будущая политика на удаление или на все действия вместе с политикой
-- очистки дала бы больше, чем задумано. Ограничивающая политика действует вместе с любой разрешающей:
-- запись моложе 3 лет не удаляет никто, что бы ни добавили позже.
CREATE POLICY hdc_audit_log_delete_guard ON hdc_audit_log AS RESTRICTIVE FOR DELETE TO hub_app
  USING (created_on < now() - interval '3 years');
COMMENT ON POLICY hdc_audit_log_delete_guard ON hdc_audit_log IS 'Запись журнала моложе 3 лет не удаляется ни при какой другой политике';
