-- Распределение по кругу в правилах автоматизации (FR-AUTO-04; план M8, задача 3): когда сотруднику последний раз
-- назначали обращение. Частичный индекс по событиям назначения: при равном числе открытых обращений следующим
-- становится тот, кому назначали раньше всех.
-- Файл выполняется вне транзакции (решение 0039, пункт 1): таблица событий большая, запись в неё не блокируется.
CREATE INDEX CONCURRENTLY IF NOT EXISTS hdt_ticket_events_i3 ON hdt_ticket_events ((payload ->> 'to'), created_on DESC) WHERE kind = 'assignee';
