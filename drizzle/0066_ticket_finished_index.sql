-- hub:no-transaction
-- Индекс счётчика "завершено за период" страницы показателей (FR-MET-01: новые И закрытые обращения; план M8,
-- задача 9): обращения, решённые или закрытые в периоде, когда бы они ни были созданы. Момент завершения: дата
-- решения, а у закрытого без решения дата закрытия. Индекс частичный: открытые обращения в него не входят, поэтому
-- работа с открытым обращением его не трогает; запись в него идёт только при решении, закрытии и повторном открытии.
-- Выражение записано через CASE, а не COALESCE: условие по COALESCE планировщик не считает безопасным для политик RLS
-- и не берёт по нему индекс, пока не проверены политики строки (запрос шёл полным просмотром таблицы).
-- Файл выполняется вне транзакции (решение 0039, пункт 1): таблица обращений большая, запись в неё не блокируется.
CREATE INDEX CONCURRENTLY IF NOT EXISTS hdt_tickets_i26
  ON hdt_tickets ((CASE WHEN resolved_on IS NOT NULL THEN resolved_on ELSE closed_on END))
  WHERE (CASE WHEN resolved_on IS NOT NULL THEN resolved_on ELSE closed_on END) IS NOT NULL;
