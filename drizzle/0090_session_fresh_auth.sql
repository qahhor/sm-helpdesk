-- Время последней настоящей проверки личности в сессии (решение 0083). По нему считается недавний вход
-- (15 минут) для смены адреса для входа, завершения других сессий и настроек сотрудников. До этого окно
-- считалось от создания сессии, и обычный вход через Smartup по открытой сессии Smartup Web без пароля
-- давал недавний вход.
ALTER TABLE auth."session" ADD COLUMN "freshAuthAt" timestamptz;

COMMENT ON COLUMN auth."session"."freshAuthAt" IS 'Колонка портала. Когда в этой сессии человек подтвердил личность: ссылка из письма или бота, пароль сотрудника, вход заново через Smartup с prompt=login. Пусто у обычного входа через Smartup. Продление сессии его не меняет';

-- Действующие сессии сотрудников открыты паролем с кодом второго фактора: их время входа и есть проверка личности.
-- Сессиям клиентов время не переносится: способ их входа по строке сессии не узнать.
UPDATE auth."session" SET "freshAuthAt" = "secondFactorAt" WHERE "secondFactorAt" IS NOT NULL;
