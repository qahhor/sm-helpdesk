-- индексу. Индекс частичный: в него входят только такие обращения, обычно ни одного. Условие записано текстом и
-- совпадает с условием запроса задачи (src/modules/hdt/core/housekeeping.ts).
-- Файл выполняется вне транзакции (решение 0039, пункт 1): таблица обращений большая, запись в неё не блокируется.
CREATE INDEX CONCURRENTLY IF NOT EXISTS hdt_tickets_i27
  ON hdt_tickets (ticket_id)
  WHERE ai_state = 'resolved_by_ai' AND status NOT IN ('resolved', 'closed');
