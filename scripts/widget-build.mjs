// Сборка загрузчика виджета (план M6, задача 4, решение 9): pnpm widget:build.
//
// Берёт src/widget/loader.js, подставляет тексты пространства widget.loader из messages/*.json и цвета и размеры из
// src/ui/tokens.css, убирает комментарии и пишет public/widget/v1/hub-widget.js. Сборщика нет: загрузчик написан так,
// что работает в браузере как есть. pnpm check сравнивает файл с результатом сборки (widgetOutOfDate) и падает, если
// файл устарел. Кеш файла на 5 минут ставит next.config.ts: данных клиентов в нём нет.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
export const WIDGET_SOURCE = resolve(root, 'src/widget/loader.js');
export const WIDGET_OUTPUT = resolve(root, 'public/widget/v1/hub-widget.js');

/** Цвета загрузчика: имя переменной в стилях загрузчика и токен слоя 1 или поправка портала. */
const COLOR_TOKENS = {
  card: '--sm-card',
  ink: '--sm-ink',
  ink2: '--sm-ink2',
  line: '--sm-line',
  pri: '--sm-pri',
  'pri-hover': '--hub-primary-hover',
  'on-pri': '--hub-on-primary',
  shadow: '--sm-shadow',
};

/** Размеры загрузчика из слоя 3 токенов. */
const SIZE_TOKENS = { text: '--text-base', control: '--spacing-control', radius: '--radius-control', card: '--radius-card', chip: '--radius-chip', font: '--font-sans' };

/**
 * Значения переменных из блоков с заданным началом (":root {", ".dark {", "@theme {"). Ссылки var() не раскрываются.
 * @param {string} css @param {string} opener
 * @returns {Map<string, string>}
 */
function declarations(css, opener) {
  /** @type {Map<string, string>} */
  const found = new Map();
  let at = css.indexOf(opener);
  while (at >= 0) {
    const end = css.indexOf('\n}', at);
    const body = css.slice(at + opener.length, end < 0 ? undefined : end);
    for (const match of body.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)) if (!found.has(match[1])) found.set(match[1], match[2].trim());
    at = css.indexOf(opener, at + opener.length);
  }
  return found;
}

/**
 * Цвета светлой и тёмной темы и размеры из src/ui/tokens.css.
 * @param {string} tokensCss
 */
export function widgetTheme(tokensCss) {
  const light = declarations(tokensCss, ':root {');
  const dark = declarations(tokensCss, '.dark {');
  const layer3 = declarations(tokensCss, '@theme {');
  /** @param {Map<string, string>} map @param {string} name */
  const literal = (map, name) => {
    const value = map.get(name);
    return value && !value.startsWith('var(') ? value : undefined;
  };
  /** @type {Record<string, string>} */
  const lightVars = {};
  /** @type {Record<string, string>} */
  const darkVars = {};
  for (const [name, token] of Object.entries(COLOR_TOKENS)) {
    const value = literal(light, token);
    if (!value) throw new Error(`widget:build: в src/ui/tokens.css нет значения ${token}`);
    lightVars[name] = value;
    darkVars[name] = literal(dark, token) ?? value;
  }
  /** @type {Record<string, string>} */
  const sizes = {};
  for (const [name, token] of Object.entries(SIZE_TOKENS)) {
    const value = layer3.get(token);
    if (!value) throw new Error(`widget:build: в src/ui/tokens.css нет значения ${token}`);
    sizes[name] = value;
  }
  // Панель на весь экран уже точки перелома tablet (ТЗ 8.3: на телефоне весь экран).
  const tablet = Number.parseFloat(layer3.get('--breakpoint-tablet') ?? '');
  if (!Number.isFinite(tablet)) throw new Error('widget:build: в src/ui/tokens.css нет --breakpoint-tablet');
  sizes.tablet = `${tablet - 0.02}px`;
  return { light: lightVars, dark: darkVars, sizes };
}

/**
 * Тексты загрузчика по языкам из messages/*.json, пространство widget.loader.
 * @param {string} messagesDir
 * @returns {Record<string, Record<string, string>>}
 */
export function widgetTexts(messagesDir) {
  /** @type {Record<string, Record<string, string>>} */
  const texts = {};
  for (const name of readdirSync(messagesDir).filter((file) => file.endsWith('.json')).sort()) {
    const messages = JSON.parse(readFileSync(resolve(messagesDir, name), 'utf8'));
    const loader = messages?.widget?.loader;
    if (!loader || typeof loader !== 'object') throw new Error(`widget:build: в messages/${name} нет widget.loader`);
    texts[name.replace('.json', '')] = loader;
  }
  return texts;
}

/**
 * Убирает комментарии исходника: строки, которые целиком комментарий, и блоки JSDoc. В строках исходника
 * последовательностей комментариев нет (это проверяет тест сборки: результат выполняется).
 * @param {string} source
 */
function stripComments(source) {
  return source
    .replace(/\/\*\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter((line) => !/^\s*\/\//.test(line) && line.trim() !== '')
    .join('\n');
}

const HEADER = '/* Smartup Hub widget loader v1. Generated by pnpm widget:build from src/widget/loader.js. Do not edit. */\n';

/**
 * Текст public/widget/v1/hub-widget.js.
 * @param {{ source?: string; tokensCss?: string; messagesDir?: string }} [input]
 */
export function buildWidget(input = {}) {
  const source = input.source ?? readFileSync(WIDGET_SOURCE, 'utf8');
  const theme = widgetTheme(input.tokensCss ?? readFileSync(resolve(root, 'src/ui/tokens.css'), 'utf8'));
  const texts = widgetTexts(input.messagesDir ?? resolve(root, 'messages'));
  const marker = (/** @type {string} */ name) => new RegExp(`/\\*__${name}__\\*/ \\{[^;]*\\}`);
  for (const name of ['HUB_TEXTS', 'HUB_THEME']) if (!marker(name).test(source)) throw new Error(`widget:build: в исходнике нет метки ${name}`);
  const filled = source.replace(marker('HUB_TEXTS'), () => JSON.stringify(texts)).replace(marker('HUB_THEME'), () => JSON.stringify(theme));
  return HEADER + stripComments(filled) + '\n';
}

/** Пустой список: файл загрузчика совпадает со сборкой. Иначе строка для pnpm check. */
export function widgetOutOfDate() {
  let current = '';
  try {
    current = readFileSync(WIDGET_OUTPUT, 'utf8');
  } catch {
    // файла нет
  }
  return current === buildWidget() ? [] : ['public/widget/v1/hub-widget.js устарел: выполните pnpm widget:build'];
}

if (import.meta.main) {
  mkdirSync(dirname(WIDGET_OUTPUT), { recursive: true });
  writeFileSync(WIDGET_OUTPUT, buildWidget());
  console.log(`Загрузчик виджета: ${WIDGET_OUTPUT}`);
}
