import { expect, test } from 'vitest';
import { parseHolidays } from '@/modules/hdr/util';

// Праздники вставкой списка (решение 25 вехи M4): даты ГГГГ-ММ-ДД или ДД.ММ.ГГГГ через строку, запятую или точку с
// запятой; текст после даты (название праздника) пропускается. Ошибочная строка называется, ничего не сохраняется.

test.each([
  ['одна дата ГГГГ-ММ-ДД', '2027-01-01', ['2027-01-01']],
  ['дата ДД.ММ.ГГГГ с названием', '01.01.2027 Новый год', ['2027-01-01']],
  ['через запятую и точку с запятой', '2027-03-21, 2027-01-01; 08.03.2027', ['2027-01-01', '2027-03-08', '2027-03-21']],
  ['по строкам с названиями и пустыми строками', '01.01.2027 Новый год\n\n08.03.2027 Международный женский день\r\n21.03.2027 Навруз', ['2027-01-01', '2027-03-08', '2027-03-21']],
  ['повтор даты не дублируется', '2027-01-01\n01.01.2027', ['2027-01-01']],
  ['пустой список', '   \n ', []],
])('%s', (_name, text, dates) => {
  expect(parseHolidays(text, 2027)).toEqual({ ok: true, dates });
});

test.each([
  ['дата другого года', '01.01.2027\n2026-12-31', 2],
  ['несуществующая дата', '2027-01-01\n08.03.2027\n31.02.2027 Ошибка', 3],
  ['не дата', 'Новый год', 1],
  ['дата без ведущего нуля', '1.1.2027', 1],
  ['тринадцатый месяц', '2027-13-01', 1],
])('%s: ошибка с номером строки', (_name, text, line) => {
  expect(parseHolidays(text, 2027)).toEqual({ ok: false, line });
});
